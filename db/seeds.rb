# Prepare data for bulk insertion
author_records = authors_and_books.keys.map do |name|
  {
    name: name,
    created_at: Time.current,
    updated_at: Time.current
  }
end

# Bulk insert authors and get their IDs
Author.insert_all(author_records)

# Create a mapping of author names to their IDs
author_name_to_id = Author.pluck(:name, :id).to_h

# Prepare book records for bulk insertion
book_records = authors_and_books.flat_map do |author_name, books|
  author_id = author_name_to_id[author_name]

  books.map do |title|
    {
      name: title,
      author_id: author_id,
      created_at: Time.current,
      updated_at: Time.current
    }
  end
end

# Bulk insert books
Book.insert_all(book_records)

puts "Seed completed: Created #{Author.count} authors and #{Book.count} books."
